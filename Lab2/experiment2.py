import os
import kagglehub
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.preprocessing import MinMaxScaler, StandardScaler
dataset_path = kagglehub.dataset_download("yasserh/titanic-dataset")
csv_file = [f for f in os.listdir(dataset_path) if f.endswith('.csv')][0]
df = pd.read_csv(os.path.join(dataset_path, csv_file))
print("--- INITIAL DATASET INFO ---")
print(df.info())
print(f"\nInitial duplicate count: {df.duplicated().sum()}")
df = df.drop_duplicates()
missing_before = df.isnull().sum()
print("\n--- MISSING VALUES BEFORE IMPUTATION ---")
print(missing_before)
df['Age'] = df['Age'].fillna(df['Age'].median())
df['Embarked'] = df['Embarked'].fillna(df['Embarked'].mode()[0])
df = df.drop(columns=['Cabin'])
missing_after = df.isnull().sum()
print("\n--- MISSING VALUES AFTER IMPUTATION ---")
print(missing_after)
plt.figure(figsize=(8, 4))
plt.bar(missing_before.index, missing_before.values, color='crimson', alpha=0.7)
plt.title('Graph 1: Missing Values per Feature (Before Imputation)')
plt.ylabel('Count')
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()
df = pd.get_dummies(df, columns=['Sex', 'Embarked'], drop_first=True)
numeric_cols = ['Age', 'Fare', 'Pclass', 'SibSp', 'Parch']
minmax_scaler = MinMaxScaler()
df_normalized = df.copy()
df_normalized[numeric_cols] = minmax_scaler.fit_transform(df[numeric_cols])
standard_scaler = StandardScaler()
df_standardized = df.copy()
df_standardized[numeric_cols] = standard_scaler.fit_transform(df[numeric_cols])
plt.figure(figsize=(12, 4))
plt.subplot(1, 3, 1)
plt.hist(df['Age'], bins=25, color='gray', edgecolor='black')
plt.title('Original Age Feature')
plt.subplot(1, 3, 2)
plt.hist(df_normalized['Age'], bins=25, color='skyblue', edgecolor='black')
plt.title('Normalized Age (0 to 1)')
plt.subplot(1, 3, 3)
plt.hist(df_standardized['Age'], bins=25, color='salmon', edgecolor='black')
plt.title('Standardized Age (Mean=0, Std=1)')
plt.tight_layout()
plt.show()
